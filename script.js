function createSheetData(prefix) {
    const sheet = [];
    for (let t = 0; t < TABLES; t++) {
        const table = [];
        for (let r = 0; r < ROWS; r++) {
            const row = [];
            for (let c = 0; c < COLS; c++) {
                row.push(`${prefix}-T${t + 1}R${r + 1}C${c + 1}`);
            }
            table.push(row);
        }
        sheet.push(table);
    }
    return sheet;
}

